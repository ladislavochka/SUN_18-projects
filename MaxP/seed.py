def main() -> None:
    Base.metadata.create_all(bind=engine)
    upgrade_schema()
    with SessionLocal() as db:
        if db.query(models.Book).count():
            print("У базі вже є книги, пропускаю.")
            return
        user = db.query(models.User).filter_by(username="demo").first()
        if not user:
            user = models.User(
                username="demo",
                email="demo@example.com",
                hashed_password=auth.get_password_hash("demo12345"),
            )
            db.add(user)
            db.flush()
        for title, author, description, genre, year, rating in BOOKS:
            db.add(models.Book(title=title, author=author, description=description,
                               genre=genre, year=year, rating=rating, owner_id=user.id))
        db.commit()
        print(f"Додано {len(BOOKS)} книг. Вхід: demo / demo12345")


if __name__ == "__main__":
    main()
